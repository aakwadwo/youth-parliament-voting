import PDFDocument from 'pdfkit'

import { formatDateTime } from '@/lib/election-report'
import { ORGANISATION_NAME, ELECTORAL_COMMISSION } from '@/lib/election'
import {
    BRAND,
    PAGE,
    LOGO_PATH,
    contentWidth,
    tricolour,
    ensureSpace,
    drawTable,
    paginate,
    renderDocument,
} from '@/lib/export/pdf-common'

/**
 * Voter registration statistics, as a printable report.
 *
 * Built to be handed to election officials and candidates, which is precisely
 * why it contains nothing but constituencies and counts. No name, number, date
 * of birth, voter id, device identifier, address or registration timestamp
 * reaches this document — the builder it renders never fetches any of them, so
 * there is nothing here to leak rather than a rule about what to omit.
 *
 * Shares its masthead, palette, table and footer with the election report and
 * the candidate register: three documents claiming to come from one Commission
 * must not arrive in three house styles.
 */

const DOC_LABEL = 'Voter registration statistics'

function drawMasthead(doc, report) {
    const width = contentWidth(doc)

    tricolour(doc, PAGE.margin, PAGE.margin, width, 5)

    let y = PAGE.margin + 26

    try {
        doc.image(LOGO_PATH, PAGE.margin, y, { width: 54 })
    } catch {
        // The report must still generate if the brand asset is missing.
    }

    doc.font('Helvetica-Bold')
        .fontSize(8)
        .fillColor(BRAND.green)
        .text(ORGANISATION_NAME.toUpperCase(), PAGE.margin + 68, y + 4, {
            width: width - 68,
            characterSpacing: 1.4,
        })

    doc.font('Helvetica-Bold')
        .fontSize(18)
        .fillColor(BRAND.ink)
        .text(report.meta.electionName, PAGE.margin + 68, doc.y + 4, { width: width - 68 })

    doc.font('Helvetica')
        .fontSize(11)
        .fillColor(BRAND.muted)
        .text(DOC_LABEL, PAGE.margin + 68, doc.y + 2, { width: width - 68 })

    y = Math.max(doc.y, PAGE.margin + 26 + 54) + 20

    // The headline figure, given the space it deserves: this is the number the
    // whole document exists to state.
    const { summary } = report
    const panelHeight = 62
    doc.roundedRect(PAGE.margin, y, width, panelHeight, 6).fillAndStroke(
        BRAND.greenLight,
        BRAND.green
    )

    const cells = [
        ['Total registered voters', summary.totalRegistered],
        ['Constituencies', summary.totalConstituencies],
        ['With registrations', summary.constituenciesWithRegistrations],
        ['With none', summary.constituenciesWithNone],
    ]
    const cellWidth = width / cells.length

    cells.forEach(([label, value], i) => {
        const cx = PAGE.margin + cellWidth * i
        doc.font('Helvetica-Bold')
            .fontSize(16)
            .fillColor(BRAND.greenDark)
            .text(value.toLocaleString('en-GB'), cx, y + 14, { width: cellWidth, align: 'center' })
        doc.font('Helvetica')
            .fontSize(8.5)
            .fillColor(BRAND.muted)
            .text(label, cx, y + 38, { width: cellWidth, align: 'center' })
    })

    y += panelHeight + 16
    doc.y = y

    const rows = [
        ['Generated', formatDateTime(report.meta.generatedAt)],
        ['Generated by', report.meta.generatedBy ?? 'Not recorded'],
        ['Issued by', ELECTORAL_COMMISSION],
    ]
    rows.forEach(([label, value]) => {
        const rowY = doc.y
        doc.font('Helvetica')
            .fontSize(9)
            .fillColor(BRAND.muted)
            .text(label, PAGE.margin, rowY, { width: 110 })
        doc.font('Helvetica-Bold')
            .fontSize(9)
            .fillColor(BRAND.ink)
            .text(value, PAGE.margin + 110, rowY, { width: width - 110 })
        doc.moveDown(0.4)
    })

    doc.moveDown(0.6)
    doc.font('Helvetica')
        .fontSize(8)
        .fillColor(BRAND.muted)
        .text(
            'Registered voters by constituency. Every constituency is listed, including those ' +
                'where nobody has registered. This is an aggregate report: it contains no voter ' +
                'names, contact details, dates of birth or any other information about an ' +
                'individual, and it contains no vote totals.',
            PAGE.margin,
            doc.y,
            { width }
        )

    doc.moveDown(1)
}

/**
 * The discrepancy note.
 *
 * Only drawn when the total and the sum of the rows disagree, which should
 * never happen. Printed rather than reconciled away, because a report whose
 * columns quietly fail to add up is worse than one that says so.
 */
function drawReconciliation(doc, summary) {
    if (summary.balanced) return

    const width = contentWidth(doc)
    ensureSpace(doc, 54)

    const y = doc.y
    doc.roundedRect(PAGE.margin, y, width, 44, 4).fillAndStroke('#FDF6F6', '#F2D9D9')

    doc.font('Helvetica-Bold')
        .fontSize(8.5)
        .fillColor(BRAND.red)
        .text('Figures do not reconcile', PAGE.margin + 12, y + 8, { width: width - 24 })

    doc.font('Helvetica')
        .fontSize(8.5)
        .fillColor(BRAND.ink)
        .text(
            `${summary.totalRegistered.toLocaleString('en-GB')} voters are on the register, but ` +
                `${summary.assigned.toLocaleString('en-GB')} are accounted for by the ` +
                `constituencies below — a difference of ${Math.abs(summary.unassigned).toLocaleString('en-GB')}. ` +
                'This should be investigated before the figures are relied upon.',
            PAGE.margin + 12,
            doc.y + 2,
            { width: width - 24 }
        )

    doc.y = y + 44
    doc.moveDown(0.6)
}

/**
 * @param report a report from `buildRegistrationReport`
 * @returns {Promise<Buffer>} the rendered PDF
 */
export function renderRegistrationStatsPdf(report) {
    const doc = new PDFDocument({
        size: 'A4',
        margin: PAGE.margin,
        // Required so paginate() can revisit pages to stamp page numbers.
        bufferPages: true,
        info: {
            Title: `${report.meta.electionName} — ${DOC_LABEL}`,
            Author: ORGANISATION_NAME,
            Subject: 'Registered voters by constituency',
            Creator: `${ORGANISATION_NAME} Voting Platform`,
            CreationDate: new Date(report.meta.generatedAt),
        },
    })

    return renderDocument(doc, () => {
        drawMasthead(doc, report)
        drawReconciliation(doc, report.summary)

        if (report.constituencies.length === 0) {
            doc.font('Helvetica-Oblique')
                .fontSize(10)
                .fillColor(BRAND.muted)
                .text('No constituencies have been set up yet.', PAGE.margin, doc.y, {
                    width: contentWidth(doc),
                })
        } else {
            // Human-readable columns only. The constituency's internal code is
            // deliberately not shown: it sat immediately left of the
            // registration count, and two right-aligned numbers side by side
            // invited a reader to mistake the identifier for the figure. It
            // remains on every row of the report object for the application's
            // own use — it is simply not something a reader of this document
            // needs, or can act on.
            drawTable(
                doc,
                [
                    { header: 'Constituency', width: 260, get: (c) => c.name },
                    { header: 'Region', width: 150, get: (c) => c.region ?? '—' },
                    {
                        header: 'Registered voters',
                        width: 89,
                        align: 'right',
                        get: (c) => c.registered,
                    },
                ],
                report.constituencies
            )

            // The total repeated under the table, so a reader who has paged
            // through the breakdown does not have to return to the masthead to
            // find out what it sums to.
            const width = contentWidth(doc)
            ensureSpace(doc, 30)
            const y = doc.y
            doc.rect(PAGE.margin, y, width, 22).fill(BRAND.greenLight)
            doc.font('Helvetica-Bold')
                .fontSize(9)
                .fillColor(BRAND.greenDark)
                .text('TOTAL REGISTERED VOTERS', PAGE.margin + 8, y + 6.5, {
                    width: width - 120,
                    lineBreak: false,
                })
            doc.font('Helvetica-Bold')
                .fontSize(9)
                .fillColor(BRAND.greenDark)
                .text(
                    report.summary.totalRegistered.toLocaleString('en-GB'),
                    PAGE.margin + width - 110,
                    y + 6.5,
                    { width: 102, align: 'right', lineBreak: false }
                )
            doc.y = y + 22
        }

        paginate(doc, `${report.meta.electionName} — ${DOC_LABEL}`)
    })
}
